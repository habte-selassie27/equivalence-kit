import { useSearchParams } from "react-router-dom";
import { canonical, findPattern } from "../../data/load";
import { EmptyState, ErrorNotice } from "../../components/Notices";
import { OnChainRun } from "../../components/OnChainRun";
import { JsonEditor } from "../../components/JsonEditor";
import { PerturbationBar } from "../../components/PerturbationBar";
import { parseJson } from "../../lib/format";
import { findDeployment } from "../../lib/genlayer";
import { engine, EngineError, type EngineStatus } from "../../worker/engine";
import { engineFailureMessage } from "../../lib/engineMessages";
import type { CompareResult, PatternId } from "../../worker/protocol";
import { PATTERN_IDS } from "../../worker/protocol";

const liveRunFailed =
  "The engine could not run this case. Retry the engine, or use the stored matrix.";

function engineErrorMessage(caught: unknown, fallback: string): string {
  if (caught instanceof EngineError) return `${caught.errorClass}: ${caught.reason}`;
  return fallback;
}

function download(filename: string, content: string, mime = "application/json") {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

const VARIATIONS: Record<PatternId, { harmless: string; harmful: string }> = {
  P1: {
    harmless:
      "verdict casing changes, the confidence band shifts by one step, cited ids reverse, and the digest is rewritten",
    harmful: "the verdict flips to the opposite allowed value",
  },
  P2: {
    harmless:
      "facts reorder, booleans become yes/no, and integer counts move by one (inside the adjacent bucket)",
    harmful:
      "booleans flip, an enum escalates, and a fact that was never on the page is added",
  },
  P3: {
    harmless: "the value moves by one and the unit casing changes",
    harmful: "the value jumps 100000 beyond the canonical one",
  },
  P4: {
    harmless: "the top two candidates swap places",
    harmful: "an unknown candidate is inserted at rank one",
  },
  P5: {
    harmless: "entities change case, reverse order, and repeat once",
    harmful: "an intruder entity is appended",
  },
  P6: {
    harmless: "the answer becomes yes/no and the evidence ids reverse",
    harmful: "the answer flips and an unknown evidence id is added",
  },
};

const CONTRACT_SKELETON = (patternId: string, className: string) => `# Generated by EquivalenceKit Pattern Builder.
# Pattern: ${patternId}
#
# Fill in the domain-specific parts (storage, methods, prompts). The primitives below
# are vendored; run \`tools/vendor.py\` to refresh them from equivalencekit/.

# BEGIN VENDORED PRIMITIVES
# (run: python3 tools/vendor.py to inline the primitives)
# END VENDORED PRIMITIVES


class ${className}(gl.Contract):
    def __init__(self):
        pass

    @gl.public.write
    def evaluate(self, *args, **kwargs):
        # TODO: deterministic checks first, then the ${patternId} consensus round.
        raise NotImplementedError
`;

export function BuilderScreen() {
  const [searchParams, setSearchParams] = useSearchParams();
  const patternId = (searchParams.get("pattern") ?? "P1") as PatternId;

  const canonicalForPattern = canonical.patterns[patternId];

  const [canonicalText, setCanonicalText] = useState(
    () => (canonicalForPattern ? JSON.stringify(canonicalForPattern.output, null, 2) : "{}"),
  );
  const [contextText, setContextText] = useState(
    () => (canonicalForPattern ? JSON.stringify(canonicalForPattern.context, null, 2) : "{}"),
  );

  const [running, setRunning] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [engineStatus, setEngineStatus] = useState<EngineStatus>(engine.getStatus());
  const [engineError, setEngineError] = useState<string | null>(engine.getLastError());

  const [identityOk, setIdentityOk] = useState<boolean | null>(null);
  const [harmlessAccepted, setHarmlessAccepted] = useState(0);
  const [harmlessTotal, setHarmlessTotal] = useState(0);
  const [harmfulRejected, setHarmfulRejected] = useState(0);
  const [harmfulTotal, setHarmfulTotal] = useState(0);
  const [hasRun, setHasRun] = useState(false);

  useEffect(
    () =>
      engine.onStatus((status) => {
        setEngineStatus(status);
        setEngineError(engine.getLastError());
      }),
    [],
  );
  useEffect(() => {
    void engine.warmUp();
  }, []);

  const engineFailed = engineStatus === "failed";

  const changePattern = (next: PatternId) => {
    const c = canonical.patterns[next];
    if (c) {
      setCanonicalText(JSON.stringify(c.output, null, 2));
      setContextText(JSON.stringify(c.context, null, 2));
    }
    const params = new URLSearchParams(searchParams);
    params.set("pattern", next);
    setSearchParams(params, { replace: true });
    setHasRun(false);
    setIdentityOk(null);
    setHarmlessAccepted(0);
    setHarmlessTotal(0);
    setHarmfulRejected(0);
    setHarmfulTotal(0);
    setError(null);
  };

  const run = async () => {
    const canonicalParsed = parseJson(canonicalText);
    const contextParsed = parseJson(contextText);
    if (!canonicalParsed.ok) {
      setError("Canonical output is not valid JSON.");
      return;
    }
    if (!contextParsed.ok) {
      setError("Context is not valid JSON.");
      return;
    }
    if (engineFailed) return;
    setRunning(true);
    setError(null);
    setHasRun(false);

    const ctx = contextParsed.ok ? contextParsed.value : {};
    const canon = canonicalParsed.value;

    try {
      const identity = (await engine.send({
        kind: "compare",
        patternId,
        leader: canon,
        validator: canon,
        context: ctx,
      })) as CompareResult;
      setIdentityOk(identity.ok);

      let harmlessOk = 0;
      const harmlessN = 10;
      for (let seed = 0; seed < harmlessN; seed++) {
        const variant = await engine.send({
          kind: "perturb",
          patternId,
          leader: canon,
          mode: "harmless",
          seed,
        });
        const result = (await engine.send({
          kind: "compare",
          patternId,
          leader: canon,
          validator: variant,
          context: ctx,
        })) as CompareResult;
        if (result.ok) harmlessOk += 1;
      }
      setHarmlessAccepted(harmlessOk);
      setHarmlessTotal(harmlessN);

      let harmfulRej = 0;
      const harmfulN = 10;
      for (let seed = 0; seed < harmfulN; seed++) {
        const variant = await engine.send({
          kind: "perturb",
          patternId,
          leader: canon,
          mode: "harmful",
          seed,
        });
        const result = (await engine.send({
          kind: "compare",
          patternId,
          leader: canon,
          validator: variant,
          context: ctx,
        })) as CompareResult;
        if (!result.ok) harmfulRej += 1;
      }
      setHarmfulRejected(harmfulRej);
      setHarmfulTotal(harmfulN);
      setHasRun(true);
    } catch (caught) {
      setError(engineErrorMessage(caught, liveRunFailed));
    } finally {
      setRunning(false);
    }
  };

  const exportSpec = () => {
    const canonicalParsed = parseJson(canonicalText);
    const contextParsed = parseJson(contextText);
    const spec = {
      pattern: patternId,
      canonical: canonicalParsed.ok ? canonicalParsed.value : null,
      context: contextParsed.ok ? contextParsed.value : null,
      rates: hasRun
        ? {
            identity: identityOk,
            harmlessAccepted,
            harmlessTotal,
            harmfulRejected,
            harmfulTotal,
          }
        : null,
    };
    download(`builder-${patternId}.json`, JSON.stringify(spec, null, 2));
  };

  const exportContract = () => {
    const className = (findPattern(patternId)?.name ?? "Builder").replace(/[^A-Za-z0-9]/g, "");
    download(
      `builder-${patternId}.py`,
      CONTRACT_SKELETON(patternId, className + "Judge"),
      "text/x-python",
    );
  };

  const spec = findPattern(patternId);
  const allClean =
    hasRun && identityOk === true && harmlessAccepted === harmlessTotal && harmfulRejected === harmfulTotal;

  return (
    <div className="stack">
      <div className="panel">
        <h1 className="panel-title">Pattern builder</h1>
        <p className="panel-note">
          Compose a canonical output and context, then run the real primitives in the
          browser. A well-tuned rule accepts the harmless variations (honest noise) and
          rejects the harmful ones (decision flips, hallucinated ids). Export the spec and
          a contract skeleton when it is tuned.
        </p>

        <label className="field-label" htmlFor="builder-pattern">
          Pattern
        </label>
        <select
          id="builder-pattern"
          value={patternId}
          onChange={(event) => changePattern(event.target.value as PatternId)}
          className="select"
        >
          {PATTERN_IDS.map((id) => (
            <option key={id} value={id}>
              {id} — {findPattern(id)?.name}
            </option>
          ))}
        </select>
        {spec ? <p className="panel-note small muted">{spec.useWhen}</p> : null}
      </div>

      <div className="panel">
        <h2 className="panel-title">Canonical leader output (JSON)</h2>
        <JsonEditor label="Canonical leader output" value={canonicalText} onChange={setCanonicalText} />
      </div>

      <div className="panel">
        <h2 className="panel-title">Context (JSON)</h2>
        <JsonEditor label="Context" value={contextText} onChange={setContextText} />
      </div>

      <div className="panel">
        <div className="row">
          <button
            type="button"
            className="button primary"
            onClick={() => void run()}
            disabled={running || engineFailed}
          >
            {running ? "Running…" : "Run tightness"}
          </button>
          <button
            type="button"
            className="button"
            onClick={exportSpec}
            disabled={running}
          >
            Export spec JSON
          </button>
          <button
            type="button"
            className="button"
            onClick={exportContract}
            disabled={running}
          >
            Export contract skeleton
          </button>
        </div>
        {engineFailed ? (
          <ErrorNotice
            message={`The engine couldn't start — ${engineFailureMessage(engineError)} The live tightness run is unavailable.`}
            action={
              <div className="btn-row">
                <button
                  type="button"
                  className="button"
                  onClick={() => {
                    void engine.retry();
                  }}
                >
                  Retry the engine
                </button>
                {engineError ? <code className="small muted">{engineError}</code> : null}
              </div>
            }
          />
        ) : null}
        {error ? <ErrorNotice message={error} /> : null}

        {hasRun ? (
          <div className="stack">
            <p className={identityOk ? "status-ok" : "status-bad"}>
              Identity case: {identityOk ? "accepted (rule reproduces itself)" : "rejected (rule does not accept identical output)"}
            </p>
            <PerturbationBar
              label="Harmless variations accepted"
              accepted={harmlessAccepted}
              rejected={harmlessTotal - harmlessAccepted}
              total={harmlessTotal}
            />
            <PerturbationBar
              label="Harmful variations rejected"
              accepted={harmfulRejected}
              rejected={harmfulTotal - harmfulRejected}
              total={harmfulTotal}
              goodWord="rejected"
              badWord="accepted"
            />
            {allClean ? (
              <p className="gaps-ok">
                No gaps found. The rule accepts honest noise and rejects hostile changes.
              </p>
            ) : (
              <p className="status-bad">
                Gaps detected: tune the tolerances or invariants and run again.
              </p>
            )}
          </div>
        ) : (
          <EmptyState title="Run tightness to see the rates for this spec." />
        )}
      </div>

      <div className="panel">
        <h2 className="panel-title">What Run tightness checks</h2>
        <p className="panel-note">
          Every run starts from your canonical output and generates variants in memory.
          Nothing in the project changes: no contract, fixture, or file is edited, and
          nothing is deployed or saved.
        </p>
        <p className="panel-note">
          <strong>Identity:</strong> the leader output compared with itself — must be
          accepted.
        </p>
        <p className="panel-note">
          <strong>Harmless, 10 seeds:</strong> {VARIATIONS[patternId].harmless}. This models
          an honest validator that read the same evidence — all 10 must be accepted.
        </p>
        <p className="panel-note">
          <strong>Harmful, 10 seeds:</strong> {VARIATIONS[patternId].harmful}. This models a
          broken or hostile leader — all 10 must be rejected.
        </p>
        <p className="panel-note">
          These are the same generators <code>ekit matrix</code> runs in CI, executed here
          in your browser with the real primitives.
        </p>
      </div>

      <div className="panel">
        <h2 className="panel-title">On chain (StudioNet)</h2>
        <p className="panel-note">
          The tightness run above is local. This panel submits one real transaction to
          the deployed VerdictJudge contract so you can watch the full lifecycle from
          this screen.
        </p>
        <OnChainRun
          deployment={findDeployment("verdict_judge")}
          method="create_judgment"
          args={[
            "Builder run",
            "ELIGIBLE,INELIGIBLE",
            '[{"item_id":"hard_income","text":"Evidence must mention income.","kind":"DETERMINISTIC","rule_kind":"EVIDENCE_CONTAINS","rule_value":"income"},{"item_id":"quality","text":"Assess whether the evidence is sufficient and relevant.","kind":"INTERPRETIVE"}]',
          ]}
          label="Run on StudioNet"
        />
      </div>

      <div className="panel">
        <h2 className="panel-title">How to use this</h2>
        <p className="panel-note">
          Start from a canonical output and the context the rule needs (verdict set,
          provided ids, tolerance). Run tightness. If a harmless variation is rejected,
          the rule is too strict — widen a tolerance or normalise more aggressively. If a
          harmful variation is accepted, the rule is too loose — add an invariant or
          tighten a threshold. Export the spec and the contract skeleton when both bars
          are clean, then wire the skeleton into your contract with
          <code> tools/vendor.py</code>.
        </p>
      </div>
    </div>
  );
}
